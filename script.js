// BACKGROUND MUSIC
const music = document.getElementById("bg-music");

if (music) {
  const savedTime = sessionStorage.getItem("musicTime");
  const shouldPlay = sessionStorage.getItem("musicPlaying");

  // Restore the song's previous position
  if (savedTime !== null) {
    music.addEventListener("loadedmetadata", () => {
      music.currentTime = Number(savedTime);
    }, { once: true });
  }

  // Save the song's position
  music.addEventListener("timeupdate", () => {
    sessionStorage.setItem("musicTime", music.currentTime);
  });

  // Try to continue playing on the next page
  if (shouldPlay === "true") {
    music.play().catch(() => {
      // Wait for the user's next interaction if playback is blocked
    });
  }

  // Start music after the user's first interaction
  document.addEventListener("click", () => {
    if (music.paused) {
      sessionStorage.setItem("musicPlaying", "true");

      music.play().catch((error) => {
        console.log("Music playback was blocked:", error);
      });
    }
  });

  // Remember playback when leaving the page
  window.addEventListener("pagehide", () => {
    sessionStorage.setItem("musicTime", music.currentTime);

    if (!music.paused) {
      sessionStorage.setItem("musicPlaying", "true");
    }
  });
}